import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const out=path.join(root,'test-output/live-ios-service',new Date().toISOString().replace(/[:.]/g,'-'));
fs.mkdirSync(out,{recursive:true});
const json=path.join(root,'tools/Newtonsoft.Json/lib/net45/Newtonsoft.Json.dll');fs.copyFileSync(json,path.join(out,'Newtonsoft.Json.dll'));
const exe=path.join(out,'LiveIosServiceProbe.exe');
const sources=['ios-client/Assets/Recovery/Runtime/CnProtocol.cs','ios-client/Assets/Recovery/Runtime/RecoveryContent.cs','tests/LiveIosServiceProbe.cs'];
const build=spawnSync(path.join(process.env.WINDIR,'Microsoft.NET/Framework64/v4.0.30319/csc.exe'),['/nologo','/platform:x64','/reference:'+json,'/reference:System.Net.Http.dll','/out:'+exe,...sources.map(file=>path.join(root,file))],{encoding:'utf8',windowsHide:true});
if(build.status!==0)throw new Error(build.stdout+build.stderr);
const character=process.argv.includes('--character');
const run=spawnSync(exe,['http://47.116.51.61:27040',out,...(character?['--character']:[])],{encoding:'utf8',windowsHide:true,timeout:120000});
if(!run.stdout.trim())throw new Error('Live probe did not produce a sanitized report.');
const report=JSON.parse(run.stdout.replace(/^\uFEFF/,''));
report.sources=sources.map(file=>({file,sha256:crypto.createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex')}));
report.publicResourceDirectory=path.relative(root,out).replaceAll('\\','/');
fs.writeFileSync(path.join(root,'evidence/ios-package-search',character?'ios-live-character-flow.json':'ios-live-service-test.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));if(run.status!==0||!report.success)process.exitCode=1;
